<#
.SYNOPSIS
  One-time (and re-runnable) production setup of Tasneem Pharmacy POS on a Windows PC.

.DESCRIPTION
  Checks Python and Node.js, installs dependencies, writes production settings, prepares the
  database, creates the first admin login, and builds the optimized frontend. Safe to run again
  after updating the app: it keeps the existing secret key, database and settings.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File deploy\windows\setup.ps1
  powershell -ExecutionPolicy Bypass -File deploy\windows\setup.ps1 -InstallAutostart
#>
param(
    [string]$PharmacyName = 'Tasneem Pharmacy',
    [string]$TimeZone = 'Asia/Karachi',
    [int]$BackendPort = 8000,
    [int]$FrontendPort = 3000,
    [ValidateSet('sqlite', 'postgres')]
    [string]$Database = 'sqlite',
    [switch]$InstallAutostart,
    [switch]$SkipBuild,
    # Optional: create the owner login without prompts (otherwise setup asks for it).
    [string]$OwnerUsername = '',
    [string]$OwnerPassword = ''
)

. "$PSScriptRoot\common.ps1"

Write-Host "Tasneem Pharmacy POS - production setup" -ForegroundColor White
Write-Note "App folder:  $RepoRoot"
Write-Note "Data folder: $DataRoot"

# ---------------------------------------------------------------- prerequisites
Write-Step 'Checking Python and Node.js'
# Each candidate: the launcher and its leading arguments (PowerShell ranges like 1..0 count backwards,
# so commands are stored as separate exe + args rather than split strings).
$candidates = @(
    @{ Exe = 'py';     Args = @('-3.12') },
    @{ Exe = 'py';     Args = @('-3') },
    @{ Exe = 'python'; Args = @() }
)
$python = $null
foreach ($c in $candidates) {
    try {
        $ver = & $c.Exe @($c.Args + '--version') 2>$null
        if ($LASTEXITCODE -eq 0 -and "$ver" -match 'Python 3\.(\d+)' -and [int]$Matches[1] -ge 12) { $python = $c; break }
    } catch { }
}
if (-not $python -and -not (Test-Path $VenvPython)) {
    Fail "Python 3.12 or newer is required. Install it from https://www.python.org/downloads/ (tick 'Add python.exe to PATH'), then run setup again."
}
if ($python) { Write-Ok "Python found: $(& $python.Exe @($python.Args + '--version'))" }

try { $nodeVer = (& node --version).Trim() } catch { $nodeVer = $null }
if (-not $nodeVer) { Fail 'Node.js 20.9 or newer is required. Install the LTS version from https://nodejs.org/, then run setup again.' }
$nv = [version]($nodeVer.TrimStart('v'))
if ($nv -lt [version]'20.9.0') { Fail "Node.js $nodeVer is too old. Install Node.js 20.9+ (LTS) from https://nodejs.org/." }
Write-Ok "Node.js found: $nodeVer"

if ((Test-PortInUse $BackendPort) -or (Test-PortInUse $FrontendPort)) {
    Write-Warn "Port $BackendPort or $FrontendPort is in use. If the POS is running, stop it first ('Stop Tasneem POS'). Continuing."
}

foreach ($d in @($DataRoot, $DataDir, $LogDir, $RunDir, $BackupDir)) { Ensure-Dir $d }

# ---------------------------------------------------------------- backend
Write-Step 'Installing backend (Python) packages'
if (-not (Test-Path $VenvPython)) {
    Invoke-Checked $python.Exe ($python.Args + @('-m', 'venv', 'venv')) $BackendDir
    Write-Ok 'Created virtual environment backend\venv'
}
Invoke-Checked $VenvPython @('-m', 'pip', 'install', '--quiet', '--disable-pip-version-check', '-r', 'requirements.txt') $BackendDir
Write-Ok 'Backend packages installed'

Write-Step 'Writing production settings (backend\.env.production)'
# Keep an existing secret key so logins stay valid across re-runs.
$secret = $null
if (Test-Path $EnvFile) {
    $line = Select-String -Path $EnvFile -Pattern '^DJANGO_SECRET_KEY=(.+)$' | Select-Object -First 1
    if ($line) { $secret = $line.Matches[0].Groups[1].Value }
}
if (-not $secret) {
    $bytes = New-Object byte[] 48
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $secret = [Convert]::ToBase64String($bytes).Replace('+', '-').Replace('/', '_').TrimEnd('=')
}
$sqlitePath = Join-Path $DataDir 'pos.sqlite3'
$envLines = @(
    '# Production settings for this PC. Generated by deploy\windows\setup.ps1 - re-run setup to change.',
    'DJANGO_DEBUG=false',
    "DJANGO_SECRET_KEY=$secret",
    'DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1',
    "CORS_ALLOWED_ORIGINS=http://localhost:$FrontendPort,http://127.0.0.1:$FrontendPort",
    'POS_LOCAL_HTTP=true',
    "TIME_ZONE=$TimeZone",
    "PHARMACY_NAME=$PharmacyName",
    'EXPIRY_WARNING_DAYS=90',
    'JWT_ACCESS_MINUTES=60',
    'JWT_REFRESH_DAYS=7'
)
if ($Database -eq 'sqlite') {
    $envLines += @('DB_ENGINE=sqlite', "SQLITE_PATH=$sqlitePath")
} else {
    $pgPassword = Read-Host 'PostgreSQL password for user "postgres"' -AsSecureString
    $plain = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($pgPassword))
    $envLines += @('DB_ENGINE=postgres', 'POSTGRES_DB=pharmacy_pos', 'POSTGRES_USER=postgres', "POSTGRES_PASSWORD=$plain", 'POSTGRES_HOST=localhost', 'POSTGRES_PORT=5432')
    Write-Note 'Make sure the database "pharmacy_pos" exists (createdb pharmacy_pos).'
}
Set-Content -Path $EnvFile -Value $envLines -Encoding ASCII
Write-Ok "Settings written ($Database database$(if ($Database -eq 'sqlite') { " at $sqlitePath" }))"

Set-BackendEnv
Write-Step 'Preparing the database'
Invoke-Checked $VenvPython @('manage.py', 'migrate', '--noinput') $BackendDir
Invoke-Checked $VenvPython @('manage.py', 'collectstatic', '--noinput', '--verbosity', '0') $BackendDir
Invoke-Checked $VenvPython @('manage.py', 'check', '--deploy', '--fail-level', 'WARNING') $BackendDir
Write-Ok 'Database ready, production checks passed'

Push-Location $BackendDir
$hasAdmin = (& $VenvPython -c "import django,os;os.environ.setdefault('DJANGO_SETTINGS_MODULE','config.settings');django.setup();from django.contrib.auth import get_user_model as g;print(g().objects.filter(is_superuser=True).exists())").Trim()
Pop-Location
if ($hasAdmin -ne 'True') {
    Write-Step 'Create the owner login (you will use this to sign in)'
    $username = $OwnerUsername
    while (-not $username) { $username = (Read-Host '    Choose a username (e.g. tasneem)').Trim() }
    $password = $OwnerPassword
    while (-not $password) {
        $p1 = Read-Host '    Choose a password (at least 8 characters)' -AsSecureString
        $p2 = Read-Host '    Type the password again' -AsSecureString
        $t1 = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($p1))
        $t2 = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($p2))
        if ($t1.Length -lt 8) { Write-Warn 'Too short. Use at least 8 characters.' }
        elseif ($t1 -ne $t2) { Write-Warn 'The two passwords do not match. Try again.' }
        else { $password = $t1 }
    }
    # Passed through environment variables (not the command line) and removed right after.
    $env:POS_OWNER_USERNAME = $username
    $env:POS_OWNER_PASSWORD = $password
    $code = "import django,os;os.environ.setdefault('DJANGO_SETTINGS_MODULE','config.settings');django.setup();" +
            "from django.contrib.auth import get_user_model as g;" +
            "g().objects.create_superuser(os.environ['POS_OWNER_USERNAME'], '', os.environ['POS_OWNER_PASSWORD'], first_name=os.environ['POS_OWNER_USERNAME'].capitalize())"
    try {
        Invoke-Checked $VenvPython @('-c', $code) $BackendDir
    } finally {
        Remove-Item Env:\POS_OWNER_USERNAME, Env:\POS_OWNER_PASSWORD -ErrorAction SilentlyContinue
    }
    Write-Ok "Owner login '$username' created"
} else {
    Write-Ok 'An owner login already exists'
}

# ---------------------------------------------------------------- frontend
Write-Step 'Building the app screens (production build)'
$frontendEnv = @(
    '# Production build settings. Generated by deploy\windows\setup.ps1.',
    "NEXT_PUBLIC_API_URL=http://localhost:$BackendPort/api",
    "NEXT_PUBLIC_PHARMACY_NAME=$PharmacyName",
    'NEXT_PUBLIC_CURRENCY=PKR',
    'NEXT_PUBLIC_LOCALE=en-PK',
    'NEXT_PUBLIC_SPEECH_LANG=en-US'
)
Set-Content -Path (Join-Path $FrontendDir '.env.production.local') -Value $frontendEnv -Encoding ASCII
$env:NEXT_TELEMETRY_DISABLED = '1'
if (-not (Test-Path (Join-Path $FrontendDir 'node_modules\next'))) {
    Invoke-Checked 'npm.cmd' @('ci', '--no-audit', '--no-fund') $FrontendDir
}
if (-not $SkipBuild) {
    Invoke-Checked 'npm.cmd' @('run', 'build') $FrontendDir
    Write-Ok 'Production build complete'
}

# ---------------------------------------------------------------- remember settings
$settings = [ordered]@{
    pharmacyName = $PharmacyName
    backendPort  = $BackendPort
    frontendPort = $FrontendPort
    database     = $Database
    sqlitePath   = $(if ($Database -eq 'sqlite') { $sqlitePath } else { $null })
    appFolder    = $RepoRoot
    setupAt      = (Get-Date).ToString('s')
}
$settings | ConvertTo-Json | Set-Content -Path $SettingsFile -Encoding ASCII
Write-Ok "Saved $SettingsFile"

if ($InstallAutostart) { & "$PSScriptRoot\install-autostart.ps1" }

Write-Host "`nSetup complete." -ForegroundColor Green
Write-Host "  Start the POS:   double-click 'Start Tasneem POS.cmd' (or run deploy\windows\start.ps1)"
Write-Host "  Open in browser: http://localhost:$FrontendPort"
if (-not $InstallAutostart) { Write-Host "  Start automatically at login + nightly backup: run deploy\windows\install-autostart.ps1" }
